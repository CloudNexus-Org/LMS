export function loadLessonQA(trackId, lessonId) {
  const custom = getStoredJSON(QA_KEY(trackId, lessonId), []);
  return [...custom, ...SEED_THREADS];
}

export function addLessonQuestion(trackId, lessonId, text, author = "You") {
  const key = QA_KEY(trackId, lessonId);
  const existing = getStoredJSON(key, []);
  const thread = {
    id: `custom-${Date.now()}`,
    author,
    time: "just now",
    text: text.trim(),
    replies: 0,
    seed: false,
  };
  const next = [thread, ...existing];
  setStoredJSON(key, next);
  return [...next, ...SEED_THREADS];
}

